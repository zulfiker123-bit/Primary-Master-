export function getMonthlyTerminalCompetencyPlan(
  classLevel: string,
  monthIndex: number
): MonthlyTerminalCompetencyPlan {
  const safeMonthIdx = Math.min(11, Math.max(0, monthIndex));
  const monthMeta = TERMINAL_MONTHS[safeMonthIdx] || TERMINAL_MONTHS[0];
  const themes = MONTH_THEMES_BY_CLASS[classLevel] || MONTH_THEMES_BY_CLASS['তৃতীয় শ্রেণি'];
  const specs = CLASS_SUBJECT_SPECS[classLevel] || CLASS_SUBJECT_SPECS['তৃতীয় শ্রেণি'];

  const subjects: SubjectMonthlyCompetency[] = specs.map((spec) => {
    const item = spec.monthlyItems[safeMonthIdx] || spec.monthlyItems[0];
    return {
      id: `tc-${classLevel}-${spec.codePrefix}-m${safeMonthIdx}`,
      code: `${spec.codePrefix}-${safeMonthIdx + 1}`,
      subject: spec.subject,
      chapterOrTheme: item.chapterOrTheme,
      competencies: item.competencies,
      verificationCriteria: item.verificationCriteria,
    };
  });

  return {
    classLevel,
    monthIndex: safeMonthIdx,
    monthName: monthMeta.name,
    term: monthMeta.term,
    monthTheme: themes[safeMonthIdx] || themes[0],
    subjects,
  };
}

export function getAllYearTerminalCompetenciesForClass(
  classLevel: string
): MonthlyTerminalCompetencyPlan[] {
  return TERMINAL_MONTHS.map((m) => getMonthlyTerminalCompetencyPlan(classLevel, m.index));
}
