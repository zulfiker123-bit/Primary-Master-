export function getMonthlyFlnQuestionSet(
  classLevel: string,
  monthIndex: number
): FlnMonthlyQuestionSet {
  const safeMonth = Math.max(0, Math.min(11, monthIndex));
  const monthMeta = FLN_MONTHS[safeMonth];
  const monthTarget = getMonthTargetForClass(safeMonth, classLevel);

  let seed: MonthlyCoreSeed;
  if (classLevel === 'তৃতীয় শ্রেণি') {
    seed = CLASS_3_MONTHLY_SEEDS[safeMonth];
  } else if (classLevel === 'চতুর্থ শ্রেণি') {
    seed = CLASS_4_MONTHLY_SEEDS[safeMonth];
  } else if (classLevel === 'পঞ্চম শ্রেণি') {
    seed = CLASS_5_MONTHLY_SEEDS[safeMonth];
  } else {
    seed = buildLowerClassMonthlySeed(classLevel, safeMonth);
  }

  return {
    monthIndex: safeMonth,
    monthName: monthMeta.name,
    classLevel,
    title: `${classLevel} — ${monthMeta.name} মাসের FLN যাচাই অনুচ্ছেদ ও প্রশ্নপত্র`,
    targetWpm: monthTarget.readingWpmGoal,
    bangla: {
      passageTitle: seed.bnTitle,
      passageText: seed.bnText,
      wordCount: countWords(seed.bnText),
      juktobornoPractice: seed.bnJukto,
      questions: seed.bnQa,
    },
    english: {
      passageTitle: seed.enTitle,
      passageText: seed.enText,
      wordCount: countWords(seed.enText),
      vocabulary: seed.enVocab,
      questions: seed.enQa,
    },
    math: {
      topicFocus: seed.mathFocus,
      mentalMath: seed.mentalMath,
      wordProblems: seed.wordProblems,
    },
    oralCheckNote: monthTarget.diagnosticPrompt,
  };
}
